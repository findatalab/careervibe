def inject_data():
    """Основная функция для наполнения базы данных"""

    # Подключаемся к БД
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # Очищаем базу
    cursor.execute('DELETE FROM question_votes')
    cursor.execute('DELETE FROM answer_votes')
    cursor.execute('DELETE FROM attachments')
    cursor.execute('DELETE FROM answers')
    cursor.execute('DELETE FROM questions')
    cursor.execute('DELETE FROM question_tags')
    cursor.execute('DELETE FROM tags')
    cursor.execute('DELETE FROM users')
    conn.commit()

    print("🔄 Создаём аккаунты...")

    # ====== СОЗДАНИЕ ПОЛЬЗОВАТЕЛЕЙ ======
    users = []
    used_names = set()
    used_emails = set()

    for i in range(NUM_USERS):
        # Генерируем уникальный никнейм
        while True:
            first_name = random.choice(FIRST_NAMES)
            last_name = random.choice(LAST_NAMES)
            nickname = f"{first_name}_{last_name}".lower()
            if nickname not in used_names:
                used_names.add(nickname)
                break

        # Генерируем уникальный email
        while True:
            prefix = random.choice(EMAIL_PREFIXES)
            if random.random() < 0.3:
                prefix += str(random.randint(1, 999))
            email = f"{prefix}@{random.choice(EMAIL_DOMAINS)}"
            if email not in used_emails:
                used_emails.add(email)
                break

        # Создаём пользователя
        password_hash = generate_password_hash('password123')
        bio = random_bio() if random.random() < 0.7 else ''
        created_at = random_date(
            datetime.now() - timedelta(days=365),
            datetime.now()
        )

        cursor.execute('''
            INSERT INTO users (email, nickname, avatar, bio, password_hash, created_at)
            VALUES (?, ?, ?, ?, ?, ?)
        ''', (email, nickname, None, bio, password_hash, created_at))

        user_id = cursor.lastrowid
        users.append({
            'id': user_id,
            'nickname': nickname,
            'created_at': created_at
        })

    conn.commit()
    print(f"✅ Создано {len(users)} пользователей")

    # ====== СОЗДАНИЕ ТЭГОВ ======
    tag_ids = {}
    for tag_name in TAGS:
        cursor.execute('INSERT OR IGNORE INTO tags (name) VALUES (?)', (tag_name,))
        cursor.execute('SELECT id FROM tags WHERE name = ?', (tag_name,))
        tag = cursor.fetchone()
        if tag:
            tag_ids[tag_name] = tag[0]

    conn.commit()
    print(f"✅ Создано {len(tag_ids)} тэгов")

    # ====== СОЗДАНИЕ ВОПРОСОВ ======
    question_ids = []
    print("📝 Создаём вопросы...")

    for i in range(NUM_QUESTIONS):
        # Выбираем случайного автора
        author = random.choice(users)

        # Выбираем вопрос из списка или генерируем случайный
        if i < len(QUESTIONS):
            q_data = QUESTIONS[i]
            title = q_data['title']
            content = q_data['content']
        else:
            # Генерируем случайный вопрос
            title = f"{random.choice(['Как', 'Что', 'Почему', 'Зачем', 'Когда', 'Где'])} " \
                    f"{random.choice(['работать', 'учиться', 'развиваться', 'найти', 'создать', 'использовать'])} " \
                    f"{random.choice(['в IT', 'в финансах', 'в карьере', 'в команде', 'в проекте'])}?"
            content = random_text_from_list(QUESTIONS[i % len(QUESTIONS)]['content'].split('\n\n')[0:2])
            content += "\n\n" + random_text_from_list(
                QUESTIONS[i % len(QUESTIONS)]['content'].split('\n\n')[2:3] if len(
                    QUESTIONS[i % len(QUESTIONS)]['content'].split('\n\n')) > 2 else [''])

        # Случайная дата создания (раньше, чем ответы)
        created_at = random_date(
            datetime.now() - timedelta(days=180),
            datetime.now() - timedelta(days=1)
        )

        # Случайное количество просмотров (от 0 до 500)
        views = random.randint(0, 500)

        cursor.execute('''
            INSERT INTO questions (title, content, user_id, created_at, views, votes)
            VALUES (?, ?, ?, ?, ?, 0)
        ''', (title, content, author['id'], created_at, views))

        q_id = cursor.lastrowid
        question_ids.append({
            'id': q_id,
            'user_id': author['id'],
            'created_at': created_at
        })

        # Добавляем тэги к вопросу (2-5 тэгов)
        num_tags = random.randint(2, 5)
        selected_tags = random.sample(list(tag_ids.keys()), min(num_tags, len(tag_ids)))
        for tag_name in selected_tags:
            tag_id = tag_ids[tag_name]
            cursor.execute('''
                INSERT OR IGNORE INTO question_tags (question_id, tag_id)
                VALUES (?, ?)
            ''', (q_id, tag_id))

        # Прогресс
        if (i + 1) % 20 == 0:
            print(f"   Создано {i + 1} вопросов")

    conn.commit()
    print(f"✅ Создано {len(question_ids)} вопросов")

    # ====== СОЗДАНИЕ ОТВЕТОВ ======
    answer_ids = []
    print("💬 Создаём ответы...")

    for i in range(NUM_ANSWERS):
        # Выбираем случайный вопрос
        question = random.choice(question_ids)

        # Выбираем случайного автора (не автора вопроса)
        available_users = [u for u in users if u['id'] != question['user_id']]
        if not available_users:
            available_users = users
        author = random.choice(available_users)

        # Выбираем случайный ответ из списка или генерируем
        if i < len(ANSWERS):
            content = ANSWERS[i]['content']
        else:
            content = random_text_from_list(ANSWERS[i % len(ANSWERS)]['content'])
            # Иногда добавляем псевдоним пользователя
            if random.random() < 0.1:
                content += f"\n\nС уважением, {author['nickname']}."

        # Случайная дата (после вопроса)
        created_at = random_date(
            question['created_at'],
            datetime.now()
        )

        # Случайный рейтинг ответа (от -5 до 15)
        votes = random.randint(-3, 15)
        is_best = False  # Отметим позже

        cursor.execute('''
            INSERT INTO answers (content, question_id, user_id, parent_answer_id, created_at, votes, is_best)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        ''', (content, question['id'], author['id'], None, created_at, votes, is_best))

        ans_id = cursor.lastrowid
        answer_ids.append({
            'id': ans_id,
            'question_id': question['id'],
            'user_id': author['id'],
            'created_at': created_at
        })

        # Прогресс
        if (i + 1) % 50 == 0:
            print(f"   Создано {i + 1} ответов")

    conn.commit()
    print(f"✅ Создано {len(answer_ids)} ответов")

    # ====== СОЗДАНИЕ ВЛОЖЕННЫХ ОТВЕТОВ (КОММЕНТАРИЕВ) ======
    print("💬 Создаём вложенные ответы (комментарии)...")

    for i in range(NUM_COMMENTS):
        # Выбираем случайный родительский ответ
        parent = random.choice(answer_ids)
        question = next((q for q in question_ids if q['id'] == parent['question_id']), None)
        if not question:
            continue

        # Выбираем случайного автора
        available_users = [u for u in users if u['id'] != parent['user_id']]
        if not available_users:
            available_users = users
        author = random.choice(available_users)

        # Генерируем короткий комментарий
        comment_templates = [
            'Отличный ответ! Полностью согласен.',
            'Спасибо за подробное объяснение!',
            'А можно поподробнее про {}?',
            'Интересно, я не знал этого.',
            'У меня был похожий опыт, спасибо за совет.',
            'Я бы добавил, что также важно учитывать {}.',
            'Спасибо, очень полезно!',
            'Какой у вас опыт в этом?',
            'Я тоже столкнулся с этим, спасибо за совет!'
        ]

        # Добавляем случайную тему в комментарий
        topics = ['этот подход', 'данную методику', 'эти технологии', 'этот инструмент']
        content = random.choice(comment_templates).format(random.choice(topics))

        # Случайная дата (после родительского ответа)
        created_at = random_date(
            parent['created_at'],
            datetime.now()
        )

        votes = random.randint(-2, 8)

        cursor.execute('''
            INSERT INTO answers (content, question_id, user_id, parent_answer_id, created_at, votes, is_best)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        ''', (content, question['id'], author['id'], parent['id'], created_at, votes, 0))

    conn.commit()
    print(f"✅ Создано {NUM_COMMENTS} вложенных ответов")

    # ====== ОТМЕТКА ЛУЧШИХ ОТВЕТОВ ======
    print("⭐ Отмечаем лучшие ответы...")

    for question in question_ids:
        # 50% вопросов имеют лучший ответ
        if random.random() < 0.5:
            # Находим ответы на этот вопрос (не вложенные)
            cursor.execute('''
                SELECT id FROM answers 
                WHERE question_id = ? AND parent_answer_id IS NULL
                ORDER BY votes DESC
            ''', (question['id'],))
            answers = cursor.fetchall()

            if answers:
                best_answer_id = answers[0][0]
                cursor.execute('''
                    UPDATE answers SET is_best = 1
                    WHERE id = ?
                ''', (best_answer_id,))

    conn.commit()
    print("✅ Лучшие ответы отмечены")

    # ====== ГОЛОСА ЗА ВОПРОСЫ ======
    print("👍 Добавляем голоса за вопросы...")

    for question in question_ids:
        # Каждый вопрос получает от 0 до 15 голосов
        num_votes = random.randint(0, 15)
        if num_votes > 0:
            # Выбираем случайных пользователей для голосования
            voters = random.sample(users, min(num_votes, len(users)))
            for voter in voters:
                if voter['id'] != question['user_id']:  # Не голосуем за свои вопросы
                    vote_value = random.choice([1, -1]) if random.random() < 0.1 else 1  # 10% негативных
                    cursor.execute('''
                        INSERT OR IGNORE INTO question_votes (user_id, question_id, vote)
                        VALUES (?, ?, ?)
                    ''', (voter['id'], question['id'], vote_value))
                    if vote_value == 1:
                        cursor.execute('UPDATE questions SET votes = votes + 1 WHERE id = ?', (question['id'],))
                    else:
                        cursor.execute('UPDATE questions SET votes = votes - 1 WHERE id = ?', (question['id'],))

    conn.commit()
    print("✅ Голоса за вопросы добавлены")

    # ====== ГОЛОСА ЗА ОТВЕТЫ ======
    print("👍 Добавляем голоса за ответы...")

    for answer in answer_ids:
        # Каждый ответ получает от 0 до 10 голосов
        num_votes = random.randint(0, 10)
        if num_votes > 0:
            voters = random.sample(users, min(num_votes, len(users)))
            for voter in voters:
                if voter['id'] != answer['user_id']:  # Не голосуем за свои ответы
                    vote_value = random.choice([1, -1]) if random.random() < 0.08 else 1  # 8% негативных
                    cursor.execute('''
                        INSERT OR IGNORE INTO answer_votes (user_id, answer_id, vote)
                        VALUES (?, ?, ?)
                    ''', (voter['id'], answer['id'], vote_value))
                    if vote_value == 1:
                        cursor.execute('UPDATE answers SET votes = votes + 1 WHERE id = ?', (answer['id'],))
                    else:
                        cursor.execute('UPDATE answers SET votes = votes - 1 WHERE id = ?', (answer['id'],))

    conn.commit()
    print("✅ Голоса за ответы добавлены")

    # ====== ИТОГИ ======
    cursor.execute('SELECT COUNT(*) FROM users')
    total_users = cursor.fetchone()[0]
    cursor.execute('SELECT COUNT(*) FROM questions')
    total_questions = cursor.fetchone()[0]
    cursor.execute('SELECT COUNT(*) FROM answers')
    total_answers = cursor.fetchone()[0]
    cursor.execute('SELECT COUNT(*) FROM tags')
    total_tags = cursor.fetchone()[0]
    cursor.execute('SELECT COUNT(*) FROM question_tags')
    total_question_tags = cursor.fetchone()[0]

    conn.close()

    print("\n" + "=" * 50)
    print("🎉 БАЗА ДАННЫХ УСПЕШНО НАПОЛНЕНА!")
    print("=" * 50)
    print(f"👤 Пользователей: {total_users}")
    print(f"📝 Вопросов: {total_questions}")
    print(f"💬 Ответов: {total_answers}")
    print(f"🏷️ Тэгов: {total_tags}")
    print(f"🔗 Связей вопрос-тэг: {total_question_tags}")
    print("=" * 50)
    print("✅ Готово к использованию!")


